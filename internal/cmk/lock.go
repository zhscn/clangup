package cmk

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"

	"go.yaml.in/yaml/v3"

	"github.com/zhscn/clangup/internal/platform"
)

const lockFileName = "cmk.lock"

// Lock pins the resolved inputs that cmk.yaml leaves floating: each
// platform's exact toolchain release, archive sha256 digests, and git commits.
type Lock struct {
	Version    int                             `yaml:"version"`
	Toolchains map[string]*LockToolchain       `yaml:"toolchains,omitempty"`
	Tools      map[string]map[string]*LockTool `yaml:"tools,omitempty"`
	Deps       map[string]*LockDep             `yaml:"dependencies,omitempty"`
	dirty      bool
}

type LockTool struct {
	Version string `yaml:"version,omitempty"`
	URL     string `yaml:"url,omitempty"`
	SHA256  string `yaml:"sha256,omitempty"`
}

type LockToolchain struct {
	Selector       string `yaml:"selector,omitempty"`
	Target         string `yaml:"target,omitempty"`
	ManifestSHA256 string `yaml:"manifest-sha256,omitempty"`
	ArtifactSHA256 string `yaml:"artifact-sha256,omitempty"`
}

type LockDep struct {
	URL    string `yaml:"url,omitempty"`
	SHA256 string `yaml:"sha256,omitempty"`
	Git    string `yaml:"git,omitempty"`
	Ref    string `yaml:"ref,omitempty"`
	Commit string `yaml:"commit,omitempty"`
	// Stamps maps platform names to the dep's content hash, which keys its
	// store entry so build/run/env resolve store paths without recomputing
	// stamps.
	Stamps map[string]string `yaml:"stamps,omitempty"`
}

func loadLock(root string) (*Lock, error) {
	lk := &Lock{Version: 1, Toolchains: map[string]*LockToolchain{}, Deps: map[string]*LockDep{}}
	path := filepath.Join(root, lockFileName)
	data, err := os.ReadFile(path)
	if err != nil {
		if os.IsNotExist(err) {
			return lk, nil
		}
		return nil, err
	}
	decoder := yaml.NewDecoder(bytes.NewReader(data))
	decoder.KnownFields(true)
	if err := decoder.Decode(lk); err != nil {
		return nil, fmt.Errorf("%s: %w", lockFileName, err)
	}
	if lk.Version != 1 {
		return nil, fmt.Errorf("%s: version must be 1", lockFileName)
	}
	if lk.Toolchains == nil {
		lk.Toolchains = map[string]*LockToolchain{}
	}
	if lk.Tools == nil {
		lk.Tools = map[string]map[string]*LockTool{}
	}
	if lk.Deps == nil {
		lk.Deps = map[string]*LockDep{}
	}
	for _, dep := range lk.Deps {
		if dep != nil && dep.Stamps == nil {
			dep.Stamps = map[string]string{}
		}
	}
	return lk, nil
}

func saveLock(root string, lk *Lock) error {
	lk.Version = 1
	for name, pin := range lk.Toolchains {
		if pin == nil || pin.empty() {
			delete(lk.Toolchains, name)
		}
	}
	for tool, platforms := range lk.Tools {
		for plat, pin := range platforms {
			if pin == nil || pin.empty() {
				delete(platforms, plat)
			}
		}
		if len(platforms) == 0 {
			delete(lk.Tools, tool)
		}
	}
	var buf bytes.Buffer
	buf.WriteString("# Generated by cmk. Commit this file.\n")
	encoder := yaml.NewEncoder(&buf)
	encoder.SetIndent(2)
	if err := encoder.Encode(lk); err != nil {
		return err
	}
	if err := encoder.Close(); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(root, lockFileName), buf.Bytes(), 0o644); err != nil {
		return err
	}
	lk.dirty = false
	return nil
}

func (pin LockToolchain) empty() bool {
	return pin.Selector == "" && pin.Target == "" && pin.ManifestSHA256 == "" && pin.ArtifactSHA256 == ""
}

func (pin LockTool) empty() bool {
	return pin.Version == "" && pin.URL == "" && pin.SHA256 == ""
}

func (lk *Lock) toolFor(tool, goos, goarch string) *LockTool {
	if lk.Tools == nil {
		lk.Tools = map[string]map[string]*LockTool{}
	}
	if lk.Tools[tool] == nil {
		lk.Tools[tool] = map[string]*LockTool{}
	}
	plat := hostPlatform(goos, goarch)
	if lk.Tools[tool][plat] == nil {
		lk.Tools[tool][plat] = &LockTool{}
	}
	return lk.Tools[tool][plat]
}

func (lk *Lock) toolPin(tool, goos, goarch string) *LockTool {
	if lk == nil || lk.Tools == nil || lk.Tools[tool] == nil {
		return nil
	}
	pin := lk.Tools[tool][hostPlatform(goos, goarch)]
	if pin == nil || pin.empty() {
		return nil
	}
	return pin
}

// hostPlatform and platformForTarget are the platform keys cmk.lock is
// indexed by; the naming is shared with clangup (see internal/platform).
func hostPlatform(goos, goarch string) string {
	return platform.Name(goos, goarch)
}

func platformForTarget(target string) string {
	return platform.FromTarget(target)
}

func (lk *Lock) toolchainFor(goos, goarch string) *LockToolchain {
	if lk.Toolchains == nil {
		lk.Toolchains = map[string]*LockToolchain{}
	}
	platform := hostPlatform(goos, goarch)
	if lk.Toolchains[platform] == nil {
		lk.Toolchains[platform] = &LockToolchain{}
	}
	return lk.Toolchains[platform]
}

func (dep *LockDep) stampFor(goos, goarch string) string {
	if dep == nil {
		return ""
	}
	return dep.Stamps[hostPlatform(goos, goarch)]
}

func (dep *LockDep) setStampFor(goos, goarch, stamp string) {
	if dep.Stamps == nil {
		dep.Stamps = map[string]string{}
	}
	dep.Stamps[hostPlatform(goos, goarch)] = stamp
}
