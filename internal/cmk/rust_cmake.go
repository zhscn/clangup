func rustCargoTargetName(cmakeName string) string {
	return "_cmk_" + cmakeName + "_cargo"
}

func cmakeLiteral(value string) string {
	eq := ""
	for strings.Index(value+"]"+eq+"]", "]"+eq+"]") != len(value) {
		eq += "="
	}
	if strings.HasPrefix(value, "\n") {
		value = "\n" + value // CMake skips one newline immediately after the opening bracket.
	}
	return "[" + eq + "[" + value + "]" + eq + "]"
}

func writeRustCMakeConfig(projectRoot, buildDir, name string, c *RustCrateCfg, cargo string, env map[string]string, nativeLibs []string) error {
	manifest := c.Manifest
	if !filepath.IsAbs(manifest) {
		manifest = filepath.Join(projectRoot, manifest)
	}
	manifest = filepath.Clean(manifest)
	if !fileExists(manifest) {
		return fmt.Errorf("rust.%s: manifest not found: %s", name, manifest)
	}

	cmakeName := rustCMakeName(name, c)
	cfgDir := rustPackageConfigDir(buildDir, cmakeName)
	var script strings.Builder
	fmt.Fprintln(&script, "# Generated by cmk.\ncmake_minimum_required(VERSION 3.20)")
	for _, key := range slices.Sorted(maps.Keys(env)) {
		fmt.Fprintf(&script, "set(%s %s)\n", cmakeLiteral("ENV{"+key+"}"), cmakeLiteral(env[key]))
	}
	fmt.Fprintln(&script, "if(release)\n  set(profile_arg --release)")
	switch c.LTO {
	case "thin", "fat":
		fmt.Fprintf(&script, "  set(ENV{CARGO_PROFILE_RELEASE_LTO} %s)\n", c.LTO)
	case "linker-plugin":
		script.WriteString(rustLinkerPluginEnv)
	}
	fmt.Fprintln(&script, "endif()\nif(debug_info)\n  set(ENV{CARGO_PROFILE_RELEASE_DEBUG} true)\nendif()")
	if c.CxxBridge {
		fmt.Fprintln(&script, `set(ENV{CXXBRIDGE_OUT_DIR} "${out}/cargo-target/cxxbridge")`)
	}
	if c.LibName != "" {
		fmt.Fprintf(&script, "set(expected_lib %s)\n", cmakeLiteral(strings.ReplaceAll(c.LibName, "-", "_")))
	}
	fmt.Fprintf(&script, "set(cargo_dir %s)\n", cmakeLiteral(filepath.Dir(manifest)))
	args := []string{cargo, "build", "--message-format=json", "--lib", "--manifest-path", manifest, "--package", rustPackageName(name, c)}
	if c.NoDefaultFeatures {
		args = append(args, "--no-default-features")
	}
	if len(c.Features) != 0 {
		args = append(args, "--features", strings.Join(c.Features, ","))
	}
	if c.Target != "" {
		target := c.Target
		if strings.HasSuffix(target, ".json") && !filepath.IsAbs(target) {
			target = filepath.Join(projectRoot, target)
		}
		args = append(args, "--target", target)
	}
	fmt.Fprintln(&script, `file(MAKE_DIRECTORY "${out}")`)
	fmt.Fprint(&script, "execute_process(COMMAND")
	for _, arg := range args {
		fmt.Fprintf(&script, " %s", cmakeLiteral(arg))
	}
	fmt.Fprint(&script, ` --target-dir "${out}/cargo-target" ${profile_arg}
  WORKING_DIRECTORY "${cargo_dir}" OUTPUT_FILE "${out}/cargo.jsonl" RESULT_VARIABLE status)
`)
	script.WriteString(rustCollectCargoOutputs)
	if c.CxxBridge {
		script.WriteString(rustStageBridge)
	}
	scriptPath := filepath.Join(cfgDir, "build-rust.cmake")
	if err := writeIfChanged(scriptPath, []byte(script.String())); err != nil {
		return err
	}

	cargoTarget := rustCargoTargetName(cmakeName)
	publicTarget := cmakeName + "::" + cmakeName
	archiveTarget := publicTarget
	if c.CxxBridge {
		archiveTarget = "_cmk_" + cmakeName + "_archive"
	}

	var config strings.Builder
	fmt.Fprintf(&config, `# Generated by cmk.
if(NOT TARGET %[1]s)
  if(CMAKE_VERSION VERSION_LESS 3.20)
    message(FATAL_ERROR "cmk Rust packages require CMake 3.20 or newer")
  endif()
  set(_cmk_rust_root %[2]s)
  set(_cmk_rust_release "$<CONFIG:Release,RelWithDebInfo,MinSizeRel>")
  set(_cmk_rust_out "${_cmk_rust_root}/config-$<CONFIG>")
  if(MSVC)
    set(_cmk_rust_lib rust.lib)
  else()
    set(_cmk_rust_lib librust.a)
  endif()
  add_custom_target(%[3]s
    COMMAND "${CMAKE_COMMAND}" "-Dout=${_cmk_rust_out}" "-Darchive=${_cmk_rust_lib}"
      "-Drelease=${_cmk_rust_release}" "-Ddebug_info=$<CONFIG:RelWithDebInfo>" -P %[4]s
    BYPRODUCTS "${_cmk_rust_out}/${_cmk_rust_lib}"
`, publicTarget, cmakeLiteral(filepath.ToSlash(filepath.Join(rustRootDir(buildDir), "crate-"+name))),
		cargoTarget, cmakeLiteral(filepath.ToSlash(scriptPath)))
	if c.CxxBridge {
		fmt.Fprintln(&config, `      "${_cmk_rust_out}/bridge.cc" "${_cmk_rust_out}/bridge-headers.hh"`)
	}
	fmt.Fprintf(&config, `    VERBATIM)
  add_library(%[1]s STATIC IMPORTED GLOBAL)
  add_dependencies(%[1]s %[2]s)
  set_property(TARGET %[1]s PROPERTY IMPORTED_LOCATION
    "${_cmk_rust_root}/config-/${_cmk_rust_lib}")
  foreach(_cmk_rust_config IN LISTS CMAKE_CONFIGURATION_TYPES CMAKE_BUILD_TYPE)
    string(TOUPPER "${_cmk_rust_config}" _cmk_rust_upper)
    set_property(TARGET %[1]s PROPERTY "IMPORTED_LOCATION_${_cmk_rust_upper}"
      "${_cmk_rust_root}/config-${_cmk_rust_config}/${_cmk_rust_lib}")
    set_property(TARGET %[1]s PROPERTY "MAP_IMPORTED_CONFIG_${_cmk_rust_upper}" "${_cmk_rust_config}")
  endforeach()
`, archiveTarget, cargoTarget)
	if len(nativeLibs) != 0 {
		fmt.Fprintf(&config, "  set_property(TARGET %s APPEND PROPERTY INTERFACE_LINK_LIBRARIES", archiveTarget)
		for _, lib := range nativeLibs {
			fmt.Fprintf(&config, " %s", cmakeLiteral(lib))
		}
		fmt.Fprintln(&config, ")")
	}
	if c.CxxBridge {
		bridgeTarget := "_cmk_" + cmakeName + "_cxxbridge"
		fmt.Fprintf(&config, `  set(%[1]s_CXXBRIDGE_INCLUDE_DIR "${_cmk_rust_out}/cargo-target/cxxbridge/include")
  set(%[1]s_CXXBRIDGE_SOURCE "${_cmk_rust_out}/bridge.cc")
  add_library(%[2]s STATIC EXCLUDE_FROM_ALL "${%[1]s_CXXBRIDGE_SOURCE}")
  add_dependencies(%[2]s %[3]s)
  target_include_directories(%[2]s PUBLIC "${%[1]s_CXXBRIDGE_INCLUDE_DIR}")
  target_include_directories(%[2]s PRIVATE "${_cmk_rust_out}/cargo-target/cxxbridge")
  if(MSVC)
    set(_cmk_rust_force_include /FI)
  else()
    set(_cmk_rust_force_include -include)
  endif()
  target_compile_options(%[2]s PUBLIC
    "$<$<COMPILE_LANGUAGE:CXX>:${_cmk_rust_force_include}${_cmk_rust_out}/bridge-headers.hh>")
  target_link_libraries(%[2]s PUBLIC %[4]s)
  add_library(%[5]s ALIAS %[2]s)
`, cmakeName, bridgeTarget, cargoTarget, archiveTarget, publicTarget)
		for _, inc := range c.CxxBridgeIncludes {
			if !filepath.IsAbs(inc) {
				inc = filepath.Join(projectRoot, inc)
			}
			fmt.Fprintf(&config, "  target_include_directories(%s PRIVATE %s)\n", bridgeTarget, cmakeLiteral(filepath.ToSlash(filepath.Clean(inc))))
		}
	}
	fmt.Fprintf(&config, "endif()\nset(%s_FOUND TRUE)\n", cmakeName)
	return writeIfChanged(filepath.Join(cfgDir, cmakeName+"Config.cmake"), []byte(config.String()))
}

//go:embed rust_collect_cargo.cmake
var rustCollectCargoOutputs string

const rustLinkerPluginEnv = `  set(ENV{CARGO_PROFILE_RELEASE_LTO} off)
  foreach(key IN ITEMS RUSTFLAGS CFLAGS CXXFLAGS)
    set(flag "-flto=thin")
    if(key STREQUAL "RUSTFLAGS")
      set(flag "-Clinker-plugin-lto")
    endif()
    string(STRIP "$ENV{${key}}" flags)
    if(NOT " ${flags} " MATCHES "[ \t]${flag}[ \t]")
      string(STRIP "${flags} ${flag}" flags)
    endif()
    set(ENV{${key}} "${flags}")
  endforeach()
`

// Keep Cargo's bridge outputs in its cache so cleaning CMake's byproducts
// does not remove files Cargo assumes are current. The header signature gives
// Ninja a known output to recheck when Cargo updates an arbitrary header.
const rustStageBridge = `set(bridge "$ENV{CXXBRIDGE_OUT_DIR}")
configure_file("${bridge}/bridge.cc" "${out}/bridge.cc" COPYONLY)
file(GLOB_RECURSE headers LIST_DIRECTORIES false FOLLOW_SYMLINKS RELATIVE "${bridge}/include" "${bridge}/include/*")
set(signature "")
foreach(header IN LISTS headers)
  file(SHA256 "${bridge}/include/${header}" hash)
  string(APPEND signature "${header}:${hash}\n")
endforeach()
string(SHA256 hash "${signature}")
file(WRITE "${out}/bridge-headers.tmp" "// cxxbridge headers: ${hash}\n")
configure_file("${out}/bridge-headers.tmp" "${out}/bridge-headers.hh" COPYONLY)
file(REMOVE "${out}/bridge-headers.tmp")
`
